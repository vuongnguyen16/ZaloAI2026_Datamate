"""Deterministic web reading copy of the current DOCX; never reads the kit."""

import argparse
import hashlib
import json
import re
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "Research/Timeline DataMate theo nhóm việc A–G.docx"
WEB = "Research/Timeline_DataMate_A-G.md"
REGISTRY = "manifests/timeline_source.json"
NS = {
    "w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main",
    "a": "http://schemas.openxmlformats.org/drawingml/2006/main",
    "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def reading_copy(root: Path) -> tuple[str, dict[str, bytes], dict]:
    source = root / SOURCE
    with zipfile.ZipFile(source) as archive:
        rels = {
            r.attrib["Id"]: r.attrib
            for r in ET.fromstring(archive.read("word/_rels/document.xml.rels"))
        }
        body = ET.fromstring(archive.read("word/document.xml")).find("w:body", NS)
        assets = {}
        counts = {"paragraphs": 0, "tables": 0, "table_rows": 0, "images": 0}

        def paragraph(node):
            pieces = []
            for child in node:
                if child.tag == f"{{{NS['w']}}}hyperlink":
                    label = "".join(child.itertext())
                    target = rels.get(child.get(f"{{{NS['r']}}}id"), {}).get("Target")
                    pieces.append(f"[{label}](<{target}>)" if target else label)
                else:
                    pieces.append(
                        "".join(t.text or "" for t in child.findall(".//w:t", NS))
                    )
            return "".join(pieces).strip()

        lines = [
            "<!-- Generated by scripts/timeline.py; DOCX remains the planning source. -->",
            "# Timeline DataMate theo nhóm việc A–G",
            "",
            "Bản đọc từ [DOCX hiện hành](<Timeline DataMate theo nhóm việc A–G.docx>). "
            "Các nhận định, nguồn nghiên cứu và model trong tài liệu là nội dung kế hoạch; "
            "cần xác minh trước khi áp dụng. "
            "Trạng thái triển khai nằm trong [state](../docs/project_state.md) "
            "và [backlog](../tasks/backlog.json).",
            "",
            f"SHA-256 DOCX: `{digest(source.read_bytes())}`.",
            "",
        ]
        for node in body:
            if node.tag == f"{{{NS['w']}}}p":
                text = paragraph(node)
                if text:
                    counts["paragraphs"] += 1
                    style = node.find("w:pPr/w:pStyle", NS)
                    style_id = (
                        style.get(f"{{{NS['w']}}}val", "") if style is not None else ""
                    )
                    heading = re.search(r"(?:Heading|heading)([1-6])", style_id)
                    if heading:
                        text = "#" * min(int(heading[1]) + 1, 6) + " " + text
                    elif re.match(r"\d+\.\d+\s", text):
                        text = "### " + text
                    elif re.match(r"\d+\.\s|[A-G]\.\s", text):
                        text = "## " + text
                    lines.extend([text, ""])
                for blip in node.findall(".//a:blip", NS):
                    rel = rels[blip.get(f"{{{NS['r']}}}embed")]
                    target = rel["Target"]
                    data = archive.read("word/" + target)
                    name = "Research/timeline_assets/" + Path(target).name
                    assets[name] = data
                    counts["images"] += 1
                    lines.extend(
                        [
                            f"![Sơ đồ giai đoạn trong DOCX](timeline_assets/{Path(target).name})",
                            "",
                        ]
                    )
            elif node.tag == f"{{{NS['w']}}}tbl":
                rows = [
                    [
                        "<br>".join(paragraph(p) for p in cell.findall("w:p", NS))
                        .replace("|", "&#124;")
                        .replace("\n", "<br>")
                        for cell in row.findall("w:tc", NS)
                    ]
                    for row in node.findall("w:tr", NS)
                ]
                if rows:
                    counts["tables"] += 1
                    counts["table_rows"] += len(rows)
                    width = max(map(len, rows))
                    for i, row in enumerate(rows):
                        lines.append(
                            "| " + " | ".join(row + [""] * (width - len(row))) + " |"
                        )
                        if i == 0:
                            lines.append("| " + " | ".join(["---"] * width) + " |")
                    lines.append("")
    return "\n".join(lines), assets, counts


def check(root: Path) -> dict:
    content, assets, counts = reading_copy(root)
    registry = json.loads((root / REGISTRY).read_text("utf-8"))
    expected = {
        SOURCE: digest((root / SOURCE).read_bytes()),
        WEB: digest(content.encode()),
    }
    expected.update({name: digest(data) for name, data in assets.items()})
    if registry["files"] != expected:
        raise ValueError(
            "timeline registry differs from the current DOCX/export; synchronize first"
        )
    for name, expected_hash in expected.items():
        if (
            not (root / name).is_file()
            or digest((root / name).read_bytes()) != expected_hash
        ):
            raise ValueError(f"timeline file is missing or stale: {name}")
    actual_assets = {
        p.relative_to(root).as_posix()
        for p in (root / "Research/timeline_assets").iterdir()
        if p.is_file()
    }
    if actual_assets != set(assets):
        raise ValueError("obsolete or missing timeline assets")
    return {"status": "current", "source_sha256": expected[SOURCE], **counts}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("export", "check"))
    args = parser.parse_args()
    if args.command == "export":
        content, assets, counts = reading_copy(ROOT)
        (ROOT / WEB).write_text(content, encoding="utf-8", newline="\n")
        for name, data in assets.items():
            (ROOT / name).parent.mkdir(parents=True, exist_ok=True)
            (ROOT / name).write_bytes(data)
        print(json.dumps(counts))
    else:
        print(json.dumps(check(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
